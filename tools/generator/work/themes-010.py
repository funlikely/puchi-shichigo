import tiling as Tl, lexicon as lx
def nugly(x):
    g = Tl.good_tilings(x)
    return 9 if not g else sum(lx.ugly_boundaries(t, i == 0, i == len(g[0]) - 1) for i, t in enumerate(g[0]))
